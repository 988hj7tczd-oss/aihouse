// 从 localStorage 读取语言偏好
function getInitialLocale() {
  if (typeof localStorage !== 'undefined') {
    return localStorage.getItem('aihouse_lang') || 'zh';
  }
  return 'zh';
}

export const locale = writable(getInitialLocale());

// 保存到 localStorage
locale.subscribe((val) => {
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('aihouse_lang', val);
  }
});

// 响应式翻译函数：在模板中用作 {$t('key')}
export const t = derived(locale, ($locale) => (key) => {
  return translations[$locale]?.[key] ?? translations.zh[key] ?? key;
});
